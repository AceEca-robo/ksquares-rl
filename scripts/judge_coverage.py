"""Which share of a game the judge (launcher/brain.py ``Solver``) covers
under a time limit per position, per board size (configs/judge_coverage.yaml).

Games of ``players`` in the simulator; every position before a move goes to
one solver per game, in game order (as the app's analyst does, which keeps
its transposition table over the game), with ``max_undrawn`` and the node
limit off. Reports per size and time limit: the share of positions with a
verdict, the largest number of undrawn lines with a verdict, the number of
undrawn lines from which on every later position got one, and the median
solve time. Writes docs/judge_coverage.md and .json.
"""

from __future__ import annotations

import argparse
import json
import time
from multiprocessing import get_context

import numpy as np

from _common import ROOT, load_config


def _game(task):
    from agents.registry import make_agent
    from launcher.brain import Solver
    from sim.board import Board

    (w, h), players, seed, limit = task
    agents = [make_agent(p, seed * 2 + i) for i, p in enumerate(players)]
    solver = Solver(w, h, None, None, limit)
    b = Board(w, h)
    out = []  # (undrawn, solved, seconds)
    while not b.done:
        t0 = time.perf_counter()
        r = solver.correct(b)
        out.append((b.geo.n_lines - b.n_drawn, r is not None, time.perf_counter() - t0))
        b.step(agents[b.player].act(b))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=str(ROOT / "configs/judge_coverage.yaml"))
    cfg = load_config(ap.parse_args().config)
    rows, raw = [], {}
    with get_context("spawn").Pool(cfg["processes"]) as pool:
        for wh in cfg["boards"]:
            for limit in cfg["time_limits"]:
                t0 = time.time()
                games = pool.map(_game, [(tuple(wh), cfg["players"], cfg["seed"] + g, limit)
                                         for g in range(cfg["games"])], chunksize=1)
                pos = [p for g in games for p in g]
                solved = [p for p in pos if p[1]]
                # per game: the undrawn count from which on every position was solved
                tails = []
                for g in games:
                    k = len(g)
                    while k > 0 and g[k - 1][1]:
                        k -= 1
                    tails.append(g[k][0] if k < len(g) else 0)
                rec = {"board": wh, "time_limit": limit, "positions": len(pos),
                       "share": len(solved) / len(pos),
                       "max_undrawn_solved": max((p[0] for p in solved), default=0),
                       "tail_median": float(np.median(tails)),
                       "n_lines": pos[0][0] if pos else 0,
                       "median_seconds_solved": float(np.median([p[2] for p in solved])) if solved else None,
                       "wall": time.time() - t0}
                raw[f"{wh[0]}x{wh[1]}@{limit}"] = rec
                rows.append(rec)
                print(json.dumps(rec), flush=True)
    L = ["# Judge coverage per board size", "",
         f"Generated by `scripts/judge_coverage.py` ({time.strftime('%Y-%m-%d %H:%M')}): "
         f"{cfg['games']} games {cfg['players'][0]} vs {cfg['players'][1]} per row, every position offered to "
         "the solver in game order (one solver per game), no max_undrawn, no node limit.", "",
         "Coverage = share of all positions of the game that got an exact verdict. Solved tail = median over "
         "games of the undrawn lines from which on every position got one (as a share of all lines in brackets).",
         "", "| board | time limit, s | coverage | solved tail (median undrawn) | max undrawn solved | "
             "median time of a solved position, s |", "|---|---:|---:|---:|---:|---:|"]
    for r in rows:
        L.append(f"| {r['board'][0]}x{r['board'][1]} | {r['time_limit']} | {100 * r['share']:.0f}% | "
                 f"{r['tail_median']:.0f} ({100 * r['tail_median'] / r['n_lines']:.0f}%) | "
                 f"{r['max_undrawn_solved']} | {r['median_seconds_solved']:.3f} |")
    (ROOT / "docs/judge_coverage.md").write_text("\n".join(L) + "\n")
    (ROOT / "docs/judge_coverage.json").write_text(json.dumps(raw, indent=1))


if __name__ == "__main__":
    main()
