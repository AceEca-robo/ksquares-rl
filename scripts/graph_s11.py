"""Part 4, series 11 of docs/plan_part4.md: is dot2c gen 16 (the app's 10x7 net, picked by the ladder) the
strongest 10x7 Dot? Matches only (configs/graph_s11.yaml): gen 16 against dot2c's accepted neighbours and the
two dot2s candidates, 200 games each, MCTS 200 both, the first 4 lines at temperature 1.

    python scripts/graph_s11.py run       # resumable: runs/graph_s11/results.json; then the report
    python scripts/graph_s11.py report    # docs/graph_s11.md
"""

from __future__ import annotations

import argparse
import json
import os
import time
from multiprocessing import get_context

from _common import ROOT, load_config
from graph_s10 import play_pair, score, wilson


def config(path="configs/graph_s11.yaml"):
    c = load_config(ROOT / path)
    base = load_config(ROOT / c["base"])
    return {**base, **c}


def label(name):
    run, gen = name.rsplit("_", 1)
    return f"{run} gen {gen}"


def verdict(cfg, res):
    """Fixed in the plan: a challenger is stronger if its score against gen 16 has the 95 % interval above 50 %;
    of several, the highest score. None stronger -> gen 16 stays."""
    best, bs = None, None
    for c in cfg["matches"]:
        r = res.get(c)
        if r is None:
            return "…", None
        lo, _ = wilson(r[1] + r[2] / 2, sum(r[:3]))     # challenger = second player of the stored pair
        if lo > 0.5 and (bs is None or 1 - score(r) > bs):
            best, bs = c, 1 - score(r)
    return ("gen 16 is the strongest of the candidates: the app keeps it" if best is None else
            f"{label(best)} beats gen 16: it replaces gen 16 in the app"), best


def cmd_run(cfg):
    import torch

    import az_eval
    from agents.az_net import Evaluator, make_net

    torch.set_num_threads(2)
    run = ROOT / cfg["run_dir"]
    run.mkdir(parents=True, exist_ok=True)
    path = run / "results.json"
    res = json.loads(path.read_text()) if path.exists() else {}

    def ev(name):
        c, ck = cfg["nets"][name]
        net = make_net(load_config(ROOT / c))
        net.load_state_dict(torch.load(ROOT / ck, map_location="cpu"))
        return Evaluator(net, cfg["device"])

    ref = ev("dot2c_16")
    with get_context("spawn").Pool(1, initializer=az_eval._oinit, initargs=({}, 0)) as pool:
        for i, c in enumerate(cfg["matches"]):
            if c in res:
                continue
            t0 = time.time()
            r = play_pair([{"ev": ref, "sims": cfg["sims"]}, {"ev": ev(c), "sims": cfg["sims"]}], cfg["games"], cfg,
                          [cfg["seed"], i], pool)
            res[c] = r
            print(f"[{time.strftime('%H:%M:%S')}] dot2c gen 16 vs {label(c)}: {r} ({time.time() - t0:.0f} s)",
                  flush=True)
            path.with_suffix(".tmp").write_text(json.dumps(res, indent=1))
            os.replace(path.with_suffix(".tmp"), path)
    cmd_report(cfg)


def cmd_report(cfg):
    res = json.loads((ROOT / cfg["run_dir"] / "results.json").read_text())
    L = ["# Part 4, series 11: is dot2c gen 16 the strongest 10x7 Dot?", "",
         f"Generated by `scripts/graph_s11.py report` ({time.strftime('%Y-%m-%d %H:%M')}). Protocol: docs/plan_part4.md "
         f"(series 11), configs/graph_s11.yaml. 10x7, {cfg['games']} games per match, MCTS {cfg['sims']} both, first "
         f"mover alternating, the first {cfg['temp_moves']} lines at temperature 1. Score % of the challenger against "
         "dot2c gen 16 with a 95 % Wilson interval.", "",
         "| challenger | wins | losses (gen 16 wins) | ties | challenger score % | 95 % |", "|---|---:|---:|---:|---:|---|"]
    for c in cfg["matches"]:
        r = res.get(c)
        if r is None:
            continue
        lo, hi = wilson(r[1] + r[2] / 2, sum(r[:3]))
        L.append(f"| {label(c)} | {r[1]} | {r[0]} | {r[2]} | {100 * (1 - score(r)):.1f} | {100 * lo:.1f}-{100 * hi:.1f} |")
    v, _ = verdict(cfg, res)
    L += ["", f"**Reading (fixed before the run): {v}.**", ""]
    notes = ROOT / "docs/graph_s11_notes.md"
    if notes.exists():
        L += [notes.read_text().rstrip(), ""]
    (ROOT / "docs/graph_s11.md").write_text("\n".join(L))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["run", "report"])
    a = ap.parse_args()
    cfg = config()
    {"run": cmd_run, "report": cmd_report}[a.cmd](cfg)


if __name__ == "__main__":
    main()
