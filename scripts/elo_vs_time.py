"""Ladder Elo with search (MCTS) and without (raw policy) against hours of training, several runs on
one axis: docs/<name>.png and docs/<name>.md.

    python scripts/elo_vs_time.py --configs configs/dot2c.yaml configs/dot2s.yaml --name dot2c_vs_dot2s

Hours of training at generation g = the summed seconds of the self-play,
train and gate phases of generations 1..g (run_dir/log.jsonl), so pauses of
a run do not count. Every accepted generation with an evaluation
(run_dir/eval/gen_*.json) is a point; Elo as in scripts/az_eval.py, with the
first config's ladder anchors. Called by az_eval.py after each evaluation
when the run config has ``compare_plot``.
"""

from __future__ import annotations

import argparse
import json
import os
import time

from _common import ROOT, load_config

from az_eval import anchors_for, fit_one

COLORS = ("#2a78d6", "#eb6834", "#1baf7a", "#eda100")   # categorical slots 1-4 (fixed order)


def curve(cfg) -> list[tuple[int, float, float, float]]:
    """[(gen, hours, mcts Elo, raw Elo)] of the evaluated accepted generations."""
    run = ROOT / cfg["run_dir"]
    try:
        state = json.loads((run / "state.json").read_text())
        log = [json.loads(ln) for ln in (run / "log.jsonl").read_text().splitlines() if ln.strip()]
    except OSError:
        return []
    secs = {}
    for e in log:
        if e.get("phase") in ("selfplay", "train", "gate") and "seconds" in e:
            secs[e["gen"]] = secs.get(e["gen"], 0.0) + e["seconds"]
    anchors = anchors_for(cfg)
    out = []
    for h in state["history"]:
        p = run / "eval" / f"gen_{h['gen']:04d}.json"
        if h["accepted"] and p.exists():
            e = json.loads(p.read_text())
            hours = sum(s for g, s in secs.items() if g <= h["gen"]) / 3600
            out.append((h["gen"], hours, fit_one(e["mcts"], anchors), fit_one(e["raw"], anchors)))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--configs", nargs="+", required=True)
    ap.add_argument("--name", required=True)
    a = ap.parse_args()
    cfgs = [load_config(ROOT / c) for c in a.configs]
    anchors = anchors_for(cfgs[0])
    runs = [(os.path.basename(c["run_dir"].rstrip("/")), curve(c)) for c in cfgs]

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(9, 5))
    for o in ("medium", "hard", "strong4"):
        if o in anchors:
            ax.axhline(anchors[o], color="#b0b0a8", lw=0.8, ls=":")
            below = o == "hard"   # 40 Elo under strong4: label it under its line
            ax.text(1.0, anchors[o] + (-10 if below else 8), o, color="#6b6b66", fontsize=9, ha="right",
                    va="top" if below else "bottom", transform=ax.get_yaxis_transform())
    for (name, pts), color in zip(runs, COLORS):
        if not pts:
            continue
        hrs, elo = [p[1] for p in pts], [p[2] for p in pts]
        ax.plot(hrs, elo, color=color, lw=2, marker="o", ms=6, label=f"{name} (MCTS {cfgs[0]['eval']['sims']})")
        ax.plot(hrs, [p[3] for p in pts], color=color, lw=1.5, ls="--", marker="o", ms=4, mfc="white",
                label=f"{name} (raw policy, no search)")
        best = max(pts, key=lambda p: p[2])
        ax.annotate(f"gen {best[0]}: {best[2]:.0f}", (best[1], best[2]), textcoords="offset points",
                    xytext=(6, 6), fontsize=9, color="#333330")
    w, h = cfgs[0]["board"]
    ax.set_xlabel("hours of training")
    ax.set_ylabel("Elo on the ladder (random = 0)")
    ax.set_title(f"{w}x{h}: " + " vs ".join(n for n, _ in runs) + ", Elo with search (solid) and without (dashed)")
    ax.grid(color="#e6e6e1", lw=0.6)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(loc="lower right", frameon=False)
    fig.tight_layout()
    fig.savefig(ROOT / f"docs/{a.name}.png", dpi=110)

    lines = [f"# {' vs '.join(n for n, _ in runs)}: Elo against hours of training", "",
             f"Generated by `scripts/elo_vs_time.py` ({time.strftime('%Y-%m-%d %H:%M')}). Hours = summed "
             "self-play + train + gate time up to the generation (pauses excluded). Elo on the "
             f"{w}x{h} ladder, anchors: " + ", ".join(f"{k} {v:.0f}" for k, v in anchors.items()) + ".", "",
             f"![]({a.name}.png)", "",
             "| run | gen | hours | MCTS Elo | raw Elo |", "|---|---:|---:|---:|---:|"]
    for name, pts in runs:
        lines += [f"| {name} | {g} | {hr:.1f} | {m:.0f} | {r:.0f} |" for g, hr, m, r in pts]
    (ROOT / f"docs/{a.name}.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
