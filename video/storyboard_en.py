#!/usr/bin/env python3
"""video/storyboard_ru.yaml -> video/storyboard_en.yaml.

The English voice is sentence for sentence the Russian one
(docs/video_script_en.md), so every cut of the Russian storyboard is moved
to the same place of the same sentence in the English voice: its time
inside the Russian sentence (video_anim.sentence_starts), as a fraction of
that sentence, lands at the same fraction of the English one. The scene's
picture after the voice keeps its length. Files go to their _en versions,
captions through CAPTIONS.

    .venv/bin/python video/storyboard_en.py
    .venv/bin/python video/video_build.py --lang en --storyboard video/storyboard_en.yaml \
        --out video/ksquares_rl_en.mp4 --srt video/ksquares_rl_en.srt --build video/build_en
"""

import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from video_anim import sentence_starts  # noqa: E402

SCENE = {"2п": "2p", "2а": "2a"}
TITLES = {"1": "Meet Dot", "2": "The game", "2p": "Pause — the double-cross", "2a": "The secret of the game",
          "3": "The training hall", "4": "How Dot learns", "5": "The ladder", "6": "Dot and her intuition",
          "7": "The ceiling", "8": "Play Dot", "9": "What next"}
CAPTIONS = {
    "красные: Dot · синие: встроенный противник KSquares": "red: Dot · blue: KSquares' built-in opponent",
    "панель приложения: куда пошла бы Dot и её перебор вариантов":
        "the app's panel: where Dot would go, and the options she goes through",
    "позиции: верные ходы обведены — их знает судья": "positions: the right moves are circled — the judge knows them",
    "голубые линии — Dot выбирает ход; звезда — Dot подумав; кольца — верные ходы":
        "light blue lines: Dot picks a move; star: Dot after thinking; rings: the right moves",
    "судья проверяет ход Dot: «сеть видит: её ход сохраняет победу»":
        "the judge checks Dot's move: \"the network sees it: its move keeps the win\"",
    "Dot из 1-го раунда (красные) против Dot из 54-го (синие), ускорено ×3":
        "Dot from round 1 (red) against Dot from round 54 (blue), 3× speed",
    "новый режим: «Обучить свою Dot» — обучение с нуля на вашей видеокарте":
        "the new mode: \"Train your own Dot\" — from scratch on your graphics card",
}

# sentence starts the pause detection gets wrong, set by hand from the voices'
# pauses (silencedetect): ru 6 "Дать Dot подумать" (the cut of storyboard_ru.yaml);
# en 6: a full pause after "with which move?" inside a sentence
FIX = {("ru", "6"): {16: 70.4}, ("en", "6"): {13: 44.4, 14: 47.4}}


def starts(lang, n):
    s, end = sentence_starts(lang, n)
    for i, t in FIX.get((lang, n), {}).items():
        s[i] = t
    return s, end


def en_file(f):
    if f.startswith("../"):
        return f.replace("_ru.png", "_en.png")
    f = f.replace("_ru.", "_en.").replace("_ru_", "_en_")
    if "_en." in f or "_en_" in f:
        return f
    stem, ext = os.path.splitext(f)
    return f"{stem}_en{ext}"


def move(t, src, dst):
    """t inside the Russian sentences src -> the same place in dst."""
    for i in range(len(src) - 1, -1, -1):
        if t >= src[i] - 1e-6:
            break
    nxt_s = src[i + 1] if i + 1 < len(src) else None
    nxt_d = dst[i + 1] if i + 1 < len(dst) else None
    if nxt_s is None:
        return dst[i] + (t - src[i])
    return dst[i] + (t - src[i]) / (nxt_s - src[i]) * (nxt_d - dst[i])


def main():
    sb = yaml.safe_load(open(os.path.join(HERE, "storyboard_ru.yaml"), encoding="utf-8"))
    sb["title"]["image"] = sb["title"]["image"].replace("_ru_", "_en_")
    for sc in sb["scenes"]:
        n_ru = str(sc["n"])
        n = SCENE.get(n_ru, n_ru)
        sc["n"] = int(n) if n.isdigit() else n
        sc["title"] = TITLES[n]
        frs = sc["fragments"]
        for fr in frs:
            fr["file"] = en_file(fr["file"])
            if "caption" in fr:
                fr["caption"] = CAPTIONS[fr["caption"]]
        if "voice" not in sc:
            continue
        sc["voice"] = f"voice_en_{n}.mp3"
        s_ru, end_ru = starts("ru", n_ru)
        s_en, end_en = starts("en", n)
        assert len(s_ru) == len(s_en), f"scene {n}: {len(s_ru)} Russian sentences, {len(s_en)} English"
        # cuts after the voice (pictures that close the scene) keep their distance to its end
        src, dst = s_ru + [end_ru], s_en + [end_en]
        t_ru, cuts = 0.0, []
        for fr in frs:
            t_ru += fr["seconds"]
            cuts.append(move(t_ru, src, dst))
        prev = 0.0
        for fr, c in zip(frs, cuts):
            fr["seconds"] = round(c - prev, 1)
            prev += fr["seconds"]
    head = ("# English cut: generated by video/storyboard_en.py from video/storyboard_ru.yaml\n"
            "# (the same cuts on the same sentences of the English voice). Do not edit by hand.\n\n")
    with open(os.path.join(HERE, "storyboard_en.yaml"), "w", encoding="utf-8") as f:
        f.write(head)
        yaml.safe_dump(sb, f, allow_unicode=True, sort_keys=False, width=110)
    print("wrote video/storyboard_en.yaml")


if __name__ == "__main__":
    main()
